#!/usr/bin/env bash
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$ROOT/build/azurearchive-spine-unity-ios-plugin"
ZIP="$ROOT/build/azurearchive-spine-unity-ios-plugin.zip"
LIB="$ROOT/build/ios-arm64/libazurearchive_spine_converter_ios.a"
HEADER="$ROOT/external/SpineSkeletonDataConverter/include/azurearchive_spine_converter_abi.h"
LICENSE="$ROOT/external/SpineSkeletonDataConverter/LICENSE"
BRIDGE="$ROOT/src/AzureArchive.UnityCompat/SpineConverterNative.Unity.cs"
test -s "$LIB"
test -s "$HEADER"
test -s "$LICENSE"
test -s "$BRIDGE"
xcrun lipo "$LIB" -verify_arch arm64
xcrun nm -gU "$LIB" | grep -q "AzureArchiveSpineJsonToBinary"
xcrun nm -gU "$LIB" | grep -q "AzureArchiveSpineConvertBuffer"
xcrun nm -gU "$LIB" | grep -q "AzureArchiveSpineFreeBuffer"
rm -rf "$OUT"
mkdir -p "$OUT/Assets/Plugins/iOS" "$OUT/Assets/Scripts"
cp "$LIB" "$OUT/Assets/Plugins/iOS/"
cp "$HEADER" "$OUT/Assets/Plugins/iOS/"
cp "$BRIDGE" "$OUT/Assets/Scripts/"
cp "$ROOT/scripts/azurearchive_spine_converter_abi.h.meta" "$OUT/Assets/Plugins/iOS/azurearchive_spine_converter_abi.h.meta"
cp "$ROOT/scripts/libazurearchive_spine_converter_ios.a.meta" "$OUT/Assets/Plugins/iOS/libazurearchive_spine_converter_ios.a.meta"
cp "$LICENSE" "$OUT/LICENSE"
cp "$ROOT/scripts/azurearchive-spine-unity-ios-plugin-README.md" "$OUT/README.md"
(cd "$OUT" && shasum -a 256 Assets/Plugins/iOS/libazurearchive_spine_converter_ios.a > SHA256SUMS.txt)
rm -f "$ZIP"
(cd "$OUT" && zip -qr "$ZIP" .)
echo "Created Unity iOS plugin package: $ZIP"
